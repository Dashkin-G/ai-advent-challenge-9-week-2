# Порядок — от «лёгкой/быстрой» к «сильной» (в таком виде и в выпадашке).
# `tier` — ресурсоёмкость для меты под ответом: лёгкая / средняя / тяжёлая.
# `price_in` / `price_out` — USD за 1M токенов (input / output). Стоимость всегда
# показывается как теоретическая (pay-as-you-go): пока жива бесплатная квота,
# реально она не списывается. None в цене → стоимость не считаем.
# ВНИМАНИЕ: цены Flash/27B — ОРИЕНТИРОВОЧНЫЕ, Max — из спеки (2/6). Сверять с
# Model Studio Pricing своей консоли.
MODELS = [
    {"code": "qwen3.6-flash", "label": "Qwen 3.6 Flash · лёгкая",  "tier": "лёгкая",  "price_in": 0.05, "price_out": 0.40},
    {"code": "qwen3.8-flash", "label": "Qwen 3.8 Flash · быстрая", "tier": "лёгкая",  "price_in": 0.15, "price_out": 0.60},
    {"code": "qwen3.6-27b",   "label": "Qwen 3.6 27B · средняя",   "tier": "средняя", "price_in": 0.70, "price_out": 2.00},
    {"code": "qwen3.8-max",   "label": "Qwen 3.8 Max · сильная",   "tier": "тяжёлая", "price_in": 2.00, "price_out": 6.00},
]

MODEL_BY_CODE = {m["code"]: m for m in MODELS}


def is_allowed_model(code: str) -> bool:
    """Разрешена ли модель к вызову (есть в безопасном реестре с Stop-on-Exhaust)."""
    return code in MODEL_BY_CODE


def model_label(code: str) -> str:
    """Человекочитаемое имя модели для интерфейса; для незнакомой — сам код."""
    m = MODEL_BY_CODE.get(code)
    return m["label"] if m else code


def model_tier(code: str) -> str | None:
    """Ресурсоёмкость модели для меты (лёгкая/средняя/тяжёлая); None — вне реестра."""
    m = MODEL_BY_CODE.get(code)
    return m["tier"] if m else None


def cost_usd(code: str, prompt_tokens: int, completion_tokens: int) -> float | None:
    """Теоретическая стоимость запроса по тарифу pay-as-you-go (USD).

    None, если цена модели не задана — тогда в интерфейсе показывается «free-квота».
    """
    m = MODEL_BY_CODE.get(code)
    if not m or m["price_in"] is None or m["price_out"] is None:
        return None
    return prompt_tokens / 1e6 * m["price_in"] + completion_tokens / 1e6 * m["price_out"]


